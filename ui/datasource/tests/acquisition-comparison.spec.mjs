import { test, expect } from '../../verification/node_modules/@playwright/test/index.mjs';

test('actual native acquisition pair shows quality sensitivity, denominators, execution identities and source-bound previews', async ({ page, request }) => {
  const data = await (await request.get('/api/datasource?subject=NOW&refresh=1')).json();
  const comparison = data.comparisons.find(item => item.acquisition);
  expect(comparison?.acquisition.collections.length).toBe(2);
  const acquisition = comparison.acquisition;
  expect(acquisition.reviews.unique_observations).toBe(32);
  expect(acquisition.reviews.units_reviewed).toBe(36);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto('/datasource');
  const ledger = page.locator('.native-collections').filter({ hasText: acquisition.collections[0].execution_id });
  await expect(ledger.getByRole('heading', { name: 'Native collection executions' })).toBeVisible();
  await expect(ledger.locator('.native-capture-counts')).toContainText('4 search-metadata snapshots + 12 document capture instances (11 unique document bodies)');
  await expect(ledger).toContainText('8 native callbacks / 12 provider logical items');
  for (const collection of acquisition.collections) await expect(ledger).toContainText(collection.execution_id);
  await page.getByRole('button', { name: /A\/B evaluation/ }).click();
  await page.getByLabel('Comparison', { exact: true }).selectOption(comparison.id);
  await expect(page.getByRole('heading', { name: `${comparison.title} (${comparison.id})`, exact: true })).toBeVisible();
  const primary = page.locator('.acquisition-metrics tbody tr').nth(0);
  await expect(primary.locator('td').nth(0)).toHaveText('18');
  await expect(primary.locator('td').nth(1)).toHaveText('15');
  await expect(page.locator('.sensitivity-row td').nth(0)).toHaveText('14');
  await expect(page.locator('.sensitivity-row td').nth(1)).toHaveText('15');
  await expect(page.locator('.acquisition-metrics')).toContainText('62.1%');
  await expect(page.locator('.acquisition-metrics')).toContainText('51.7%');
  await expect(page.locator('.acquisition-metrics')).toContainText('Does not establish resolution of all 12 underlying gaps');
  await expect(page.locator('.acquisition-comparison')).toContainText('4 unique observations (8 arm-bound references)');
  await expect(page.locator('.acquisition-comparison')).toContainText('32 unique observations (36 arm-bound references)');
  await expect(page.locator('.financial-context-note')).toContainText('FY2026Q3');
  await expect(page.locator('.financial-context-note')).toContainText('FY2026Q2');
  await expect(page.locator('.financial-context-note')).toContainText('not AI-specific recognized revenue or original-publication detection latency');
  await page.screenshot({ path: '../runtime/datasource-acquisition-desktop.png' });
  const b = acquisition.collections.find(item => item.arm === 'B');
  await page.getByLabel('Collection arm', { exact: true }).selectOption('B');
  await expect(page.locator('.acquisition-units [role=status]')).toContainText(`Showing ${b.units.length} of ${b.units_total} arm B units`);
  const first = page.locator('.acquisition-unit').first();
  await first.locator('summary').click();
  await expect(first.locator('blockquote')).toHaveText(b.units[0].quote);
  await expect(first).toContainText(b.units[0].source_sha256);
  const source = b.sources.find(item => item.id === b.units[0].source_id);
  await expect(first.getByRole('link', { name: /Open captured source/ })).toHaveAttribute('href', source.url);
  await page.setViewportSize({ width: 360, height: 800 });
  await expect(page.getByLabel('Collection arm', { exact: true })).toHaveValue('B');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: '../runtime/datasource-acquisition-mobile.png' });
  await page.getByLabel('Comparison', { exact: true }).selectOption('now_captured_regrade_1.0.2');
  await expect(page.getByRole('heading', { name: 'Matched case differences' })).toBeVisible();
  await expect(page.locator('.acquisition-comparison')).toHaveCount(0);
});


test('two actual registered rounds keep sensitivity ordering and reverse-review counts distinct', async ({ page, request }) => {
  const data = await (await request.get('/api/datasource?subject=NOW&refresh=1')).json();
  const ids = ['NOW-current-acquisition-20261102-v1', 'NOW-current-acquisition-20261102-v2'];
  for (const id of ids) expect(data.comparisons.find(item => item.id === id), `actual API must project registered ${id}; no injected comparison`).toBeTruthy();
  await page.goto('/datasource');
  await page.getByRole('button', { name: /A\/B evaluation/ }).click();
  const selector = page.getByLabel('Comparison', { exact: true });
  await selector.selectOption(ids[0]);
  await expect(page.locator('.acquisition-comparison h2')).toContainText(ids[0]);
  await expect(page.locator('.acquisition-comparison .notice-warning')).toContainText('This sensitivity reverses the count ordering.');
  await expect(page.locator('.acquisition-metrics tbody tr').first()).toContainText('18');
  await expect(page.locator('.sensitivity-row')).toContainText('14');
  await selector.selectOption(ids[1]);
  await expect(page.locator('.acquisition-comparison h2')).toContainText(ids[1]);
  await expect(selector.locator('option:checked')).toContainText(ids[1]);
  await expect(page.locator('.acquisition-comparison .notice-warning')).toContainText('Arm B leads under both counts.');
  await expect(page.locator('.acquisition-comparison .notice-warning')).not.toContainText('reverses');
  const row = page.locator('.acquisition-metrics tbody tr').first();
  await expect(row.locator('td').nth(0)).toHaveText('15');
  await expect(row.locator('td').nth(1)).toHaveText('22');
  await expect(page.locator('.sensitivity-row td').nth(0)).toHaveText('15');
  await expect(page.locator('.sensitivity-row td').nth(1)).toHaveText('19');
  await expect(page.locator('.recorded-review-counts')).toContainText('Forward review: A 15 / B 22');
  await expect(page.locator('.recorded-review-counts')).toContainText('Reverse review: A 15 / B 23');
  await expect(page.locator('.acquisition-comparison')).toContainText('Recorded core metrics do not agree');
  const second = data.comparisons.find(item => item.id === ids[1]).acquisition;
  for (const collection of second.collections) await expect(page.locator('.acquisition-comparison .native-collections')).toContainText(collection.execution_id);
  await expect(page.locator('.acquisition-comparison .native-collections')).toContainText('Cost: Unknown');
  const selected = second.collections.find(item => item.arm === 'B');
  await page.getByLabel('Collection arm', { exact: true }).selectOption('B');
  await expect(page.locator('.acquisition-units [role=status]')).toContainText(`Showing 8 of ${selected.units_total} arm B units. ${selected.units_truncated} previews omitted`);
  const preview = page.locator('.acquisition-unit').first();
  await preview.locator('summary').click();
  await expect(preview.locator('blockquote')).toHaveText(selected.units[0].quote);
  await expect(preview).toContainText(selected.units[0].source_sha256);
  const source = selected.sources.find(item => item.id === selected.units[0].source_id);
  await expect(preview.getByRole('link', { name: /Open captured source/ })).toHaveAttribute('href', source.url);
  await page.screenshot({ path: '../runtime/datasource-acquisition-v2.png' });

});
